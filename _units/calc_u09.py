"""EP9 練習題答案：讓它令人滿足（即時回報、時間不一致、習慣追蹤、習慣契約）。
雙曲折現 V = A/(1+kD)；指數折現 V = A·δ^D；
連續達成機率 p^n；「絕不錯過兩次」= n 天內沒有連續兩天漏做的機率（動態規劃）；
習慣契約期望罰款 = 漏做機率 × 天數 × 每次罰金。"""
k = 0.05  # 每天的雙曲折現參數
V = lambda A, D: A / (1 + k * D)
print("Q1 150 元延後 90 天的主觀價值 =", round(V(150, 90), 2), "；100 元延後 60 天 =", round(V(100, 60), 2))
print("   對照：今天 100 元 =", V(100, 0), "；30 天後 150 元 =", V(150, 30))
# Q2 兩個選項同時往後推 t 天，何時偏好反轉：100/(1+k t) = 150/(1+k(t+30))
# 解：100(1+k(t+30)) = 150(1+k t)  →  100 + 100k t + 3000k = 150 + 150k t  → t = (100+3000k-150)/(50k)
t = (100 + 100 * k * 30 - 150) / (50 * k)
print("Q2 兩選項一起往後推幾天時無差異 =", round(t, 2), "天 → 驗證", round(V(100, t), 3), round(V(150, t + 30), 3))
# 指數折現沒有偏好反轉：比值與 t 無關
d = 0.98
print("   指數折現比值（t=0, t=60）=", round(150 * d**30 / 100, 4), round(150 * d**90 / (100 * d**60), 4))
p, n = 0.9, 30
print("Q3 每天 90% 做到，連續 30 天不斷鏈 =", round(p**n, 4))
# Q4 DP：狀態 = 結尾連續漏做天數(0或1)
a, b = p, 1 - p  # 第 1 天：做到 / 漏做
for _ in range(n - 1):
    a, b = (a + b) * p, a * (1 - p)
print("Q4 30 天內從未連續漏兩天 =", round(a + b, 4))
print("Q5 契約期望罰款 0.03×90×200 =", round(0.03 * 90 * 200, 2))
print("補 +50% 後要跌多少才回原點 =", round((1 - 100 / 150) * 100, 2), "%")
