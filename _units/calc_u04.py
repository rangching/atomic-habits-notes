"""EP4 練習題答案：覺察與意圖。
習慣計分卡（書中範例 12 項）、指差確認錯誤率、執行意圖的相對提升、習慣堆疊的條件機率鏈。"""
card = {"起床": "=", "關鬧鐘": "=", "看手機": "-", "上廁所": "=", "量體重": "+", "洗澡": "+",
        "刷牙": "+", "用牙線": "+", "擦體香劑": "+", "晾毛巾": "=", "換衣服": "=", "泡茶": "+"}
plus = sum(v == "+" for v in card.values()); minus = sum(v == "-" for v in card.values())
print("Q1 +", plus, " -", minus, " =", sum(v == "=" for v in card.values()), " 淨分 =", plus - minus)
print("Q2 指差確認：每百次 2.38 → 0.38，錯誤減少 % =", round((2.38 - 0.38) / 2.38 * 100, 1))
print("Q3 運動研究（書中轉述）38% → 91%，倍數 =", round(91 / 38, 2))
print("Q4 流感疫苗：33.1% 加 4.2 個百分點，相對提升 % =", round(4.2 / 33.1 * 100, 1))
print("Q5 錨點 0.95，三個新習慣各 0.9 的條件機率，第三個發生的機率 =", round(0.95 * 0.9**3, 3))
